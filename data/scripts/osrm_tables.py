"""Fetch real road (car) and walking (foot) times between every curated point from public OSRM
servers, once, and store them in ``data/seed/road_times.json``.

Points: every neighborhood centre, attraction and restaurant in the seed (about 130). The
tables are requested in small blocks (sources x destinations) with a pause between requests,
which keeps us well inside the public servers' fair-use rules (no heavy or repeated use):
about 30 requests in total, run by hand when the dataset changes.

The stored values are raw OSRM minutes and kilometres. They are tagged ``estimated`` (not
``api``): they were fetched once, not in the current run, and OSRM has no live traffic. The
local provider adds the taxi pickup time and a traffic factor when it builds a leg
(``data/heuristics.py``).

Usage::

    uv run python -m data.scripts.osrm_tables            # fetch and write the seed file
    uv run python -m data.scripts.build_matrix           # then refresh the neighborhood matrix
    uv run python -m data.build_db                       # and rebuild the database
"""

from __future__ import annotations

import json
import time
from datetime import date
from pathlib import Path
from typing import Any

import httpx

from core.config import get_settings

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "seed"
OUT = SEED / "road_times.json"
BLOCK = 34  # points per side of a block: 68 coordinates per request
PAUSE_S = 1.5


def points() -> list[tuple[str, float, float]]:
    """(id, lat, lon) for every neighborhood, attraction and restaurant in the seed."""
    out: list[tuple[str, float, float]] = []
    for name, key in (
        ("neighborhoods", "neighborhoods"),
        ("attractions", "attractions"),
        ("restaurants", "restaurants"),
    ):
        data = json.loads((SEED / f"{name}.json").read_text(encoding="utf-8"))
        for rec in data[key]:
            loc = rec["location"]
            out.append((rec["id"], float(loc["lat"]), float(loc["lon"])))
    return out


def fetch_table(
    client: httpx.Client, base: str, pts: list[tuple[str, float, float]]
) -> tuple[list[list[float | None]], list[list[float | None]]]:
    """Full minutes and km matrices for ``pts``, requested block by block."""
    n = len(pts)
    minutes: list[list[float | None]] = [[None] * n for _ in range(n)]
    km: list[list[float | None]] = [[None] * n for _ in range(n)]
    blocks = [list(range(i, min(i + BLOCK, n))) for i in range(0, n, BLOCK)]
    for src in blocks:
        for dst in blocks:
            idx = src + [d for d in dst if d not in src]
            coords = ";".join(f"{pts[i][2]:.6f},{pts[i][1]:.6f}" for i in idx)
            pos = {i: k for k, i in enumerate(idx)}
            params = {
                "sources": ";".join(str(pos[i]) for i in src),
                "destinations": ";".join(str(pos[i]) for i in dst),
                "annotations": "duration,distance",
            }
            body = _get(client, f"{base}/table/v1/driving/{coords}", params)
            for a, row_s, row_m in zip(src, body["durations"], body["distances"], strict=True):
                for b, s, m in zip(dst, row_s, row_m, strict=True):
                    minutes[a][b] = None if s is None else round(s / 60, 1)
                    km[a][b] = None if m is None else round(m / 1000, 2)
            time.sleep(PAUSE_S)
    return minutes, km


def _get(client: httpx.Client, url: str, params: dict[str, str]) -> Any:
    for attempt in range(3):
        resp = client.get(url, params=params)
        if resp.status_code == 429 or resp.status_code >= 500:
            time.sleep(5 * (attempt + 1))
            continue
        resp.raise_for_status()
        body = resp.json()
        if body.get("code") != "Ok":
            raise RuntimeError(f"OSRM error: {body.get('code')} {body.get('message')}")
        return body
    raise RuntimeError(f"OSRM kept failing: {url[:80]}")


def main() -> int:  # pragma: no cover - network
    settings = get_settings()
    pts = points()
    profiles: dict[str, Any] = {}
    with httpx.Client(headers={"User-Agent": settings.http_user_agent}, timeout=60.0) as client:
        for profile, base in (("car", settings.osrm_car_url), ("foot", settings.osrm_foot_url)):
            print(f"{profile}: {len(pts)} points from {base} ...", flush=True)
            minutes, km = fetch_table(client, base.rstrip("/"), pts)
            profiles[profile] = {"server": base, "minutes": minutes, "km": km}
    doc = {
        "_note": "Generated by data/scripts/osrm_tables.py: OSRM route times (no live traffic) "
        "between every curated point. Matrices are indexed by `ids` (row = from, column = to).",
        "source": "estimated",
        "reference": "OSRM routes on OpenStreetMap data (car: project-osrm.org demo server, "
        "foot: routing.openstreetmap.de); no live traffic",
        "as_of": date.today().isoformat(),
        "ids": [p[0] for p in pts],
        "profiles": profiles,
    }
    OUT.write_text(json.dumps(doc, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
