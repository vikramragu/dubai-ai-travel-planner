"""Pre-compute the neighborhood-to-neighborhood travel matrix (tagged ``estimated``).

Writes ``data/seed/travel_matrix.json`` with one entry per unordered neighborhood pair and mode
(lookups are symmetric). Taxi and walking use the stored OSRM routes in
``data/seed/road_times.json`` when present (``data/scripts/osrm_tables.py``); metro and abra,
and any pair OSRM couldn't route, use the heuristic.

Usage::

    uv run python -m data.scripts.build_matrix
"""

from __future__ import annotations

import json
from itertools import combinations
from pathlib import Path

from data.dataset import RoadTimes
from data.heuristics import BASIS, ROAD_BASIS, estimate_minutes, road_leg
from schemas import Neighborhood, TransportMode, TravelMatrix, TravelMatrixEntry, estimated

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "seed"
MODES = (TransportMode.TAXI, TransportMode.WALK, TransportMode.METRO, TransportMode.ABRA)


PROFILE = {TransportMode.TAXI: "car", TransportMode.WALK: "foot"}


def _road(
    roads: RoadTimes | None, a: str, b: str, mode: TransportMode
) -> tuple[float, float] | None:
    """Stored OSRM (minutes, km), from a to b (lookups are symmetric, so use one direction)."""
    if roads is None or mode not in PROFILE or PROFILE[mode] not in roads.profiles:
        return None
    try:
        i, j = roads.ids.index(a), roads.ids.index(b)
    except ValueError:
        return None
    prof = roads.profiles[PROFILE[mode]]
    m, k = prof.minutes[i][j], prof.km[i][j]
    return None if m is None or k is None else (m, k)


def build(neighborhoods: list[Neighborhood], roads: RoadTimes | None = None) -> TravelMatrix:
    entries = []
    road_basis = ROAD_BASIS + (f", routed {roads.as_of}" if roads and roads.as_of else "")
    for a, b in combinations(sorted(neighborhoods, key=lambda n: n.id), 2):
        for mode in MODES:
            route = _road(roads, a.id, b.id, mode)
            if route is not None:
                leg = road_leg(
                    mode, route[0], route[1], a.location.distance_km(b.location),
                    hood_a=a.id, hood_b=b.id,
                )  # fmt: skip
                if leg is not None:
                    entries.append(
                        TravelMatrixEntry(
                            from_id=a.id,
                            to_id=b.id,
                            mode=mode,
                            duration_min=estimated(leg[0], road_basis),
                            distance_km=estimated(leg[1], road_basis),
                        )
                    )
                continue
            est = estimate_minutes(
                a.location,
                b.location,
                mode,
                station_a=a.metro_station,
                station_b=b.metro_station,
                hood_a=a.id,
                hood_b=b.id,
            )
            if est is None:
                continue
            minutes, km = est
            entries.append(
                TravelMatrixEntry(
                    from_id=a.id,
                    to_id=b.id,
                    mode=mode,
                    duration_min=estimated(minutes, BASIS),
                    distance_km=estimated(km, BASIS),
                )
            )
    return TravelMatrix(entries=entries)


def main() -> int:  # pragma: no cover
    raw = json.loads((SEED / "neighborhoods.json").read_text(encoding="utf-8"))
    hoods = [Neighborhood.model_validate(h) for h in raw["neighborhoods"]]
    road_file = SEED / "road_times.json"
    roads = (
        RoadTimes.model_validate(
            {k: v for k, v in json.loads(road_file.read_text()).items() if k != "_note"}
        )
        if road_file.exists()
        else None
    )
    matrix = build(hoods, roads)
    (SEED / "travel_matrix.json").write_text(
        json.dumps(
            {
                "_note": "Generated by data/scripts/build_matrix.py (taxi/walk from stored OSRM "
                "routes, metro/abra heuristic). "
                "Lookups are symmetric: one entry per unordered pair and mode.",
                **matrix.model_dump(mode="json", exclude_none=True),
            },
            indent=1,
        )
        + "\n",
        encoding="utf-8",
    )
    by_mode: dict[str, int] = {}
    for e in matrix.entries:
        by_mode[e.mode.value] = by_mode.get(e.mode.value, 0) + 1
    print(f"{len(matrix.entries)} entries: {by_mode}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
